# frozen_string_literal: true

# Pins the gem's public surface: every public constant, class method and instance method of Phlex::Shadcn::* that is not tagged
# `@api private`, plus the generated yielded-root helpers of each compound root, as listed in test/fixtures/public_api.txt.
# A change to the surface is a reviewed decision, never a side effect.
#
# When this test fails because you changed the surface on purpose:
#   1. regenerate the fixture: `bundle exec rake public_api:update` (from gems/phlex-shadcn);
#   2. review the fixture diff in the PR: every added line is a commitment, every removed line breaks consumers;
#   3. add a CHANGELOG entry: required for added or removed public names, and for a changed signature (a removed or renamed
#      keyword breaks callers, a new optional keyword is an "Added" line).
# A change that only touches `@api private` names or method bodies does not change the fixture.
#
# Private means: tagged `@api private` (on the object or on any class or module it lives in), declared `private`/`protected`,
# or a `private_constant`. YARD reads the tags, so the test and `yard --hide-api private` agree on what is public.

require "test_helper"
require "yard"

# Builds the snapshot text from the YARD registry (tags and signatures) and from reflection (generated helpers).
module PublicApiSnapshot
  GEM_DIR = File.expand_path("..", __dir__)
  FIXTURE = File.join(GEM_DIR, "test/fixtures/public_api.txt")
  HEADER = <<~TEXT
    # Public API of phlex-shadcn: generated by `bundle exec rake public_api:update`, checked by test/public_api_test.rb.
    # Sections: constants, class methods (.), instance methods (#), generated yielded-root helpers (root#helper).
    # Never edit by hand; review the diff of a regeneration and add a CHANGELOG entry (see the test header).
  TEXT

  CLASS_STRING_NAME = /(\ACLASSES|_CLASSES?|_STYLE|_STYLE_VARS|\AVISUALLY_HIDDEN|_TRANSFORM)\z/

  module_function

  def build
    registry_lines = public_objects.flat_map { |object| describe(object) }.sort
    helper_lines = helpers.sort
    [ HEADER, "## constants and methods", *registry_lines, "", "## generated yielded-root helpers", *helper_lines, "" ].join("\n")
  end

  def public_objects
    YARD::Registry.clear
    YARD.parse(Dir[File.join(GEM_DIR, "lib/**/*.rb")].reject { |path| path.end_with?("icons/catalog.rb") })
    YARD::Registry.all(:class, :module, :constant, :method).select { |object| public?(object) && object.path.start_with?("Phlex::Shadcn") }
  end

  def public?(object)
    chain = []
    cursor = object
    until cursor.nil? || cursor.root?
      chain << cursor
      cursor = cursor.parent
    end
    chain.none? { |link| link.tag(:api)&.text == "private" || link.visibility != :public }
  end

  def describe(object)
    case object.type
    when :class then [ "class #{object.path}#{superclass_suffix(object)}" ]
    when :module then [ "module #{object.path}" ]
    when :constant then class_string_constant?(object) ? [] : [ "const #{object.path}" ]
    else [ "#{object.scope == :class ? 'class_method' : 'method'} #{object.path} #{signature(object)}".strip ]
    end
  end

  # Tailwind class strings and inline style fragments are implementation details of the DOM, not API (ruby-gem-conventions R5):
  # they are `@api private` where tagged; this filter keeps the ones not tagged yet out of the baseline.
  def class_string_constant?(constant) = constant.name.to_s.match?(CLASS_STRING_NAME)

  def superclass_suffix(object)
    superclass = object.superclass&.path
    superclass && superclass != "Object" ? " < #{superclass}" : ""
  end

  def signature(method)
    params = method.parameters.map do |name, default|
      if default
        name.end_with?(":") ? "#{name} #{default}" : "#{name} = #{default}"
      else
        name
      end
    end
    "(#{params.join(', ')})"
  end

  # `root#helper`: `Base.const_added` defines one helper per nested part class of a root, so each public nested component
  # class of the registry is one helper of its parent (checked against the real class, so a missing helper fails loudly).
  def helpers
    parts = public_objects.select { |object| object.type == :class && object.namespace.type == :class }
    parts = parts.select { |part| Object.const_get(part.path) < Phlex::Shadcn::Base }
    parts.map do |part|
      root = Object.const_get(part.namespace.path)
      helper = part.name.to_s.gsub(/([a-z\d])([A-Z])/, '\1_\2').downcase
      raise "#{root} has no generated helper ##{helper}" unless root.public_method_defined?(helper)

      "#{part.namespace.path}##{helper}"
    end
  end
end

class PublicApiTest < Minitest::Test
  def test_public_surface_matches_the_fixture
    actual = PublicApiSnapshot.build
    if ENV["PUBLIC_API_UPDATE"]
      File.write(PublicApiSnapshot::FIXTURE, actual)
      skip "fixture regenerated (PUBLIC_API_UPDATE)"
    end

    expected = File.read(PublicApiSnapshot::FIXTURE)

    assert_equal expected, actual, failure_message(expected, actual)
  end

  def test_fixture_has_no_class_string_constant_and_no_private_names
    lines = File.readlines(PublicApiSnapshot::FIXTURE, chomp: true)
    offenders = lines.grep(/\Aconst .*::#{PublicApiSnapshot::CLASS_STRING_NAME.source}/)

    assert_empty offenders, "class-string constants are not public API and must not be pinned"
  end

  private

  def failure_message(expected, actual)
    added = actual.lines - expected.lines
    removed = expected.lines - actual.lines
    <<~MESSAGE
      The public surface of phlex-shadcn changed.
      Added:
      #{added.map { |line| "  + #{line}" }.join}
      Removed:
      #{removed.map { |line| "  - #{line}" }.join}
      If this is intended: bundle exec rake public_api:update, review the fixture diff and add a CHANGELOG entry.
    MESSAGE
  end
end
